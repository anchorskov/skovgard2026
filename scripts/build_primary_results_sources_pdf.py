def register_fonts() -> None:
    required = {
        "Bitter-SemiBold": FONT_DIR / "Bitter-SemiBold.ttf",
        "Bitter-Bold": FONT_DIR / "Bitter-Bold.ttf",
        "SourceSans3": FONT_DIR / "SourceSans3-Regular.ttf",
        "SourceSans3-SemiBold": FONT_DIR / "SourceSans3-SemiBold.ttf",
        "SourceSans3-Bold": FONT_DIR / "SourceSans3-Bold.ttf",
    }
    missing = [str(path) for path in required.values() if not path.exists()]
    if missing:
        raise FileNotFoundError("Missing font files: " + ", ".join(missing))
    for name, path in required.items():
        pdfmetrics.registerFont(TTFont(name, str(path)))
    pdfmetrics.registerFontFamily(
        "SourceSans3",
        normal="SourceSans3",
        bold="SourceSans3-Bold",
        italic="SourceSans3",
        boldItalic="SourceSans3-Bold",
    )


def draw_page(canvas, doc) -> None:
    width, height = letter
    canvas.saveState()
    canvas.setFillColor(BONE)
    canvas.rect(0, 0, width, height, stroke=0, fill=1)

    canvas.setStrokeColor(DUST)
    canvas.setLineWidth(0.6)
    canvas.line(doc.leftMargin, 0.56 * inch, width - doc.rightMargin, 0.56 * inch)

    canvas.setFont("SourceSans3-SemiBold", 8.5)
    canvas.setFillColor(CHARCOAL)
    canvas.drawString(doc.leftMargin, 0.35 * inch, "SKOVGARD FOR SENATE  |  SOURCE RECORD")
    canvas.drawRightString(width - doc.rightMargin, 0.35 * inch, f"Page {doc.page}")
    canvas.restoreState()


def build_pdf() -> Path:
    register_fonts()
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    title_style = ParagraphStyle(
        "Title",
        fontName="Bitter-Bold",
        fontSize=25,
        leading=29,
        textColor=CHARCOAL,
        alignment=TA_CENTER,
        spaceAfter=4,
    )
    subtitle_style = ParagraphStyle(
        "Subtitle",
        fontName="Bitter-SemiBold",
        fontSize=15,
        leading=19,
        textColor=RUST,
        alignment=TA_CENTER,
        spaceAfter=9,
    )
    kicker_style = ParagraphStyle(
        "Kicker",
        fontName="SourceSans3-Bold",
        fontSize=8.5,
        leading=10,
        textColor=EMBER,
        alignment=TA_CENTER,
        spaceAfter=10,
    )
    body_style = ParagraphStyle(
        "Body",
        fontName="SourceSans3",
        fontSize=10.2,
        leading=13.5,
        textColor=CHARCOAL,
        alignment=TA_LEFT,
        spaceAfter=7,
    )
    note_style = ParagraphStyle(
        "Note",
        fontName="SourceSans3",
        fontSize=8.8,
        leading=11.5,
        textColor=CHARCOAL,
        alignment=TA_LEFT,
    )
    county_style = ParagraphStyle(
        "County",
        fontName="Bitter-SemiBold",
        fontSize=10.3,
        leading=13,
        textColor=CHARCOAL,
        alignment=TA_LEFT,
    )
    link_style = ParagraphStyle(
        "Link",
        fontName="SourceSans3-SemiBold",
        fontSize=9.4,
        leading=11.5,
        textColor=EMBER,
        alignment=TA_LEFT,
        spaceAfter=1,
    )
    url_style = ParagraphStyle(
        "URL",
        fontName="SourceSans3",
        fontSize=7.0,
        leading=8.8,
        textColor=SAGE,
        alignment=TA_LEFT,
        splitLongWords=True,
    )
    table_header_style = ParagraphStyle(
        "TableHeader",
        fontName="SourceSans3-Bold",
        fontSize=8.5,
        leading=10,
        textColor=BONE,
        alignment=TA_LEFT,
    )
    status_style_official = ParagraphStyle(
        "StatusOfficial",
        fontName="SourceSans3-Bold",
        fontSize=8.6,
        leading=10.5,
        textColor=SAGE,
        alignment=TA_LEFT,
    )
    status_style_unofficial = ParagraphStyle(
        "StatusUnofficial",
        fontName="SourceSans3-Bold",
        fontSize=8.6,
        leading=10.5,
        textColor=SANDSTONE,
        alignment=TA_LEFT,
    )
    status_style_not_yet = ParagraphStyle(
        "StatusNotYet",
        fontName="SourceSans3-Bold",
        fontSize=8.6,
        leading=10.5,
        textColor=RUST,
        alignment=TA_LEFT,
    )
    STATUS_STYLES = {
        OFFICIAL: status_style_official,
        UNOFFICIAL: status_style_unofficial,
        NOT_YET: status_style_not_yet,
    }

    doc = SimpleDocTemplate(
        str(OUTPUT_PATH),
        pagesize=letter,
        leftMargin=0.68 * inch,
        rightMargin=0.68 * inch,
        topMargin=0.56 * inch,
        bottomMargin=0.76 * inch,
        title="2026 Wyoming Primary Candidate Results: Official County Sources",
        author="Skovgard for Senate",
        subject="Official Wyoming county clerk election-result source pages",
        creator="Skovgard for Senate",
    )

    story = []
    accent = Table([["", "", "", ""]], colWidths=[1.63 * inch] * 4, rowHeights=[0.12 * inch])
    accent.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (0, 0), CHARCOAL),
                ("BACKGROUND", (1, 0), (1, 0), EMBER),
                ("BACKGROUND", (2, 0), (2, 0), SANDSTONE),
                ("BACKGROUND", (3, 0), (3, 0), SAGE),
            ]
        )
    )
    story.append(accent)
    story.append(Spacer(1, 0.20 * inch))
    story.append(Paragraph("OFFICIAL SOURCE RECORD", kicker_style))
    story.append(Paragraph("2026 Wyoming Primary<br/>Candidate Results", title_style))
    story.append(Paragraph("County clerk election-result pages", subtitle_style))
    story.append(
        Paragraph(
            "This source packet supports the updated Candidates voter guide. Each link goes to an official Wyoming county website maintained by the county clerk or elections office. The Status column reflects each county's certification status as of the date below: Official (certified/final results loaded), Unofficial (election-night results loaded, certification pending), or Not yet published (no results loaded on the site yet). Open a county source to review the results and supporting reports published by that county.",
            body_style,
        )
    )

    note = Table(
        [[Paragraph("SOURCE NOTE", table_header_style), Paragraph("County page labels reflect each county's own publication status. A county may replace, relabel, or add reports after this packet is prepared. The source page remains the authority for its current publication.", note_style)]],
        colWidths=[1.0 * inch, 5.5 * inch],
    )
    note.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (0, 0), CHARCOAL),
                ("BACKGROUND", (1, 0), (1, 0), colors.HexColor("#F1ECE1")),
                ("BOX", (0, 0), (-1, -1), 0.7, DUST),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 7),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
            ]
        )
    )
    story.append(note)
    story.append(Spacer(1, 0.18 * inch))

    table_data = [
        [
            Paragraph("COUNTY", table_header_style),
            Paragraph("STATUS", table_header_style),
            Paragraph("OFFICIAL ELECTION SOURCE", table_header_style),
        ]
    ]
    for county, page_title, url, status in COUNTY_SOURCES:
        safe_url = escape(url, {'"': '&quot;'})
        source_cell = [
            Paragraph(f'<link href="{safe_url}" color="#B22234"><u>{escape(page_title)}</u></link>', link_style),
            Paragraph(f'<link href="{safe_url}" color="#7A8A6B">{escape(url)}</link>', url_style),
        ]
        table_data.append([
            Paragraph(escape(county), county_style),
            Paragraph(escape(status), STATUS_STYLES[status]),
            source_cell,
        ])

    official_count = sum(1 for *_, status in COUNTY_SOURCES if status == OFFICIAL)
    unofficial_count = sum(1 for *_, status in COUNTY_SOURCES if status == UNOFFICIAL)
    not_yet_count = sum(1 for *_, status in COUNTY_SOURCES if status == NOT_YET)

    sources_table = Table(table_data, colWidths=[0.95 * inch, 1.05 * inch, 4.50 * inch], repeatRows=1, splitByRow=1)
    table_commands = [
        ("BACKGROUND", (0, 0), (-1, 0), CHARCOAL),
        ("BOX", (0, 0), (-1, -1), 0.75, DUST),
        ("LINEBELOW", (0, 1), (-1, -1), 0.35, DUST),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, 0), 7),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 7),
        ("TOPPADDING", (0, 1), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 1), (-1, -1), 5),
    ]
    for row_index in range(1, len(table_data)):
        if row_index % 2 == 0:
            table_commands.append(("BACKGROUND", (0, row_index), (-1, row_index), colors.HexColor("#F1ECE1")))
    sources_table.setStyle(TableStyle(table_commands))
    story.append(sources_table)
    story.append(Spacer(1, 0.13 * inch))
    story.append(
        Paragraph(
            f"Prepared August 27, 2026: {official_count} of 23 counties Official, "
            f"{unofficial_count} Unofficial, {not_yet_count} Not yet published. "
            "This packet lists source pages and each county's certification status on the "
            "Candidates voter guide as of the date above. It does not replace the official "
            "reports or certifications published by each county, and county status changes "
            "as more counties certify -- see candidates.skovgard2026.org for the current state.",
            note_style,
        )
    )

    doc.build(story, onFirstPage=draw_page, onLaterPages=draw_page)
    return OUTPUT_PATH


if __name__ == "__main__":
    output = build_pdf()
    print(output)
