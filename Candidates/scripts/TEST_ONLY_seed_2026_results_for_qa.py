def sql_str(v):
    if v is None:
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def sql_int(v):
    return "NULL" if v is None else str(int(v))


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", required=True)
    args = p.parse_args()

    out = [
        "-- Generated by TEST_ONLY_seed_2026_results_for_qa.py, results_test branch only.",
        "-- Synthetic vote counts, real 2026 filed candidate names. Not real results.",
        "",
        "INSERT OR IGNORE INTO election_sources "
        "(source_key, election_id, county, source_role, status, notes) "
        "SELECT 'test-qa|natrona|wy-2026-primary', "
        "(SELECT id FROM election_events WHERE election_key = 'wy-2026-primary'), "
        f"{sql_str(COUNTY)}, 'manual', 'active', "
        "'TEST DATA: results_test branch QA seed, delete before real 2026 data arrives';",
        "",
        "INSERT OR IGNORE INTO election_source_snapshots "
        "(source_id, snapshot_seq, sha256, parser_name, is_unofficial, verification_status) "
        "SELECT (SELECT id FROM election_sources WHERE source_key = 'test-qa|natrona|wy-2026-primary'), "
        "1, 'test-qa-synthetic-sha', 'test_only_manual_seed', 1, 'verified';",
        "",
    ]

    by_party_group = {}
    for contest_name, level, district, county, candidates_list in CONTESTS:
        by_party = {}
        for name, party, votes in candidates_list:
            by_party.setdefault(party_norm(party), []).append((name, votes))

        for party, entries in by_party.items():
            contest_key = "|".join([ELECTION_KEY, level, slugify(contest_name), party.lower()])
            county_clause = sql_str(county) if county else "NULL"
            out.append(
                "INSERT OR IGNORE INTO election_contests "
                "(contest_key, election_id, contest_name_raw, contest_name_normalized, level, district, "
                "ballot_party, reporting_scope, county) SELECT "
                f"{sql_str(contest_key)}, (SELECT id FROM election_events WHERE election_key = 'wy-2026-primary'), "
                f"{sql_str(contest_name)}, {sql_str(contest_name)}, {sql_str(level)}, {sql_int(district)}, "
                f"{sql_str(party)}, "
                f"{sql_str('county' if level == 'county' else ('legislative_district' if level in ('wy_senate','wy_house') else 'statewide'))}, "
                f"{county_clause};"
            )
            out.append(
                "INSERT OR IGNORE INTO election_snapshot_contests "
                "(snapshot_id, contest_id, precincts_reporting, precincts_total, reporting_status) SELECT "
                "(SELECT id FROM election_source_snapshots WHERE source_id = "
                "(SELECT id FROM election_sources WHERE source_key = 'test-qa|natrona|wy-2026-primary')), "
                f"(SELECT id FROM election_contests WHERE contest_key = {sql_str(contest_key)}), "
                "1, 1, 'partial';"
            )
            for name, votes in entries:
                key = f"test-qa|{contest_key}|{name}"
                out.append(
                    "INSERT OR IGNORE INTO election_results_rows "
                    "(result_row_key, snapshot_contest_id, row_type, candidate_name_raw, votes) SELECT "
                    f"{sql_str(key)}, "
                    "(SELECT sc.id FROM election_snapshot_contests sc "
                    "JOIN election_source_snapshots s ON s.id = sc.snapshot_id "
                    "JOIN election_sources src ON src.id = s.source_id "
                    "JOIN election_contests c ON c.id = sc.contest_id "
                    "WHERE src.source_key = 'test-qa|natrona|wy-2026-primary' "
                    f"AND c.contest_key = {sql_str(contest_key)}), "
                    f"'candidate', {sql_str(name)}, {sql_int(votes)};"
                )

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"OK: wrote {args.out}")


if __name__ == "__main__":
    main()
