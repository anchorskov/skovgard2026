# results_test branch only. Not part of the production ingestion pipeline,
# not intended to ever be merged to main. Seeds clearly-synthetic
# wy-2026-primary results, using real filed 2026 candidate names so the
# structural-match/aggregation/leading-badge logic in race/[id].astro can
# be exercised end to end against realistic data, since no real 2026
# results exist anywhere yet.
#
# Every row from this script carries source_role='manual' and a notes
# field starting with "TEST DATA", and source_key is prefixed
# "test-qa|" specifically so it can be found and deleted in one pass:
#   DELETE FROM election_results_rows WHERE snapshot_contest_id IN (
#     SELECT sc.id FROM election_snapshot_contests sc
#     JOIN election_source_snapshots s ON s.id = sc.snapshot_id
#     JOIN election_sources src ON src.id = s.source_id
#     WHERE src.source_key LIKE 'test-qa|%');
#   DELETE FROM election_snapshot_contests WHERE snapshot_id IN (
#     SELECT s.id FROM election_source_snapshots s
#     JOIN election_sources src ON src.id = s.source_id
#     WHERE src.source_key LIKE 'test-qa|%');
#   DELETE FROM election_source_snapshots WHERE source_id IN (
#     SELECT id FROM election_sources WHERE source_key LIKE 'test-qa|%');
#   DELETE FROM election_sources WHERE source_key LIKE 'test-qa|%';
#   DELETE FROM election_contests WHERE contest_key LIKE 'wy-2026-primary|%'
#     AND id NOT IN (SELECT DISTINCT contest_id FROM election_snapshot_contests);
# (that last DELETE only removes contests this script itself created and
# nothing else still references it; safe even if run alongside real data)

