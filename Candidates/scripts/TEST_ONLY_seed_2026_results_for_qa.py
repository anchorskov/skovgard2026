def slugify(value):
    value = re.sub(r"[^\w\s-]", "", value.lower())
    return re.sub(r"[\s_]+", "-", value).strip("-")

def party_norm(p):
    return {"Republican": "REP", "Democratic": "DEM", "DEM": "DEM", "REP": "REP"}.get(p, p[:3].upper())

